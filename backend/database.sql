DROP TABLE IF EXISTS partidos;
DROP TABLE IF EXISTS jugadores;
DROP TABLE IF EXISTS equipos;

CREATE TABLE equipos (
  id      SERIAL PRIMARY KEY,
  nombre  VARCHAR(80) NOT NULL UNIQUE,
  ciudad  VARCHAR(60),
  estadio VARCHAR(80)
);

CREATE TABLE jugadores (
  id        SERIAL PRIMARY KEY,
  nombre    VARCHAR(80) NOT NULL,
  posicion  VARCHAR(20) NOT NULL CHECK (posicion IN ('Portero','Defensa','Medio','Delantero')),
  dorsal    INT CHECK (dorsal BETWEEN 1 AND 99),
  goles     INT NOT NULL DEFAULT 0 CHECK (goles >= 0),
  equipo_id INT NOT NULL REFERENCES equipos(id) ON DELETE CASCADE
);

CREATE TABLE partidos (
  id              SERIAL PRIMARY KEY,
  fecha           DATE NOT NULL,
  local_id        INT NOT NULL REFERENCES equipos(id),
  visitante_id    INT NOT NULL REFERENCES equipos(id),
  goles_local     INT NOT NULL CHECK (goles_local >= 0),
  goles_visitante INT NOT NULL CHECK (goles_visitante >= 0),
  CHECK (local_id <> visitante_id)
);

